"""Build an India-wide Jenks map and a separate QGIS project using PyQGIS."""

from __future__ import annotations

import argparse
import gc
import json
import logging
import os
import re
import sqlite3
import subprocess
import sys
import tempfile
from pathlib import Path

import geopandas as gpd


LOGGER = logging.getLogger("agri_gis.stage6")
PROJECT_ROOT = Path(__file__).resolve().parents[1]
MAP_OUTPUT = PROJECT_ROOT / "output" / "maps"
MAP_DATA_FILE = MAP_OUTPUT / "India_Rice_Yield_Data.gpkg"
MAP_DATA_LAYER = "india_rice_yield"
MAP_IMAGE = MAP_OUTPUT / "India_Rice_Yield_Map.png"
MAP_PDF = MAP_OUTPUT / "India_Rice_Yield_Map.pdf"
QGIS_PROJECT = MAP_OUTPUT / "India_Rice_Yield_Project.qgz"
OUTPUT_MARKER = MAP_OUTPUT / ".india_rice_yield_pipeline.json"
OUTPUT_MARKER_CONTENT = "India Rice Yield map generated by the agriculture GIS pipeline."
MAP_CRS = "EPSG:7755"


def _read_spatial_data() -> gpd.GeoDataFrame:
    from src.pipeline_utils import create_database_engine

    engine = create_database_engine()
    try:
        with engine.connect() as connection:
            spatial = gpd.read_postgis(
                "SELECT * FROM public.rice_district_spatial ORDER BY boundary_fid",
                connection,
                geom_col="geom",
            )
    finally:
        engine.dispose()
    if len(spatial) != 735:
        raise ValueError(
            f"Expected 735 spatial district rows for the map; found {len(spatial)}."
        )
    if spatial.crs is None or spatial.crs.to_epsg() != 4326:
        raise ValueError(
            f"Map source must use EPSG:4326; found {spatial.crs!s}."
        )
    if spatial.geometry.isna().any() or spatial.geometry.is_empty.any():
        raise ValueError("Map source contains missing or empty geometries.")
    if (~spatial.geometry.is_valid).any():
        raise ValueError("Map source contains invalid geometries.")
    if spatial["crop_yield"].notna().sum() < 5:
        raise ValueError("Fewer than five district yields are available to map.")
    return spatial


def _check_existing_outputs() -> None:
    expected_outputs = (MAP_DATA_FILE, MAP_IMAGE, MAP_PDF, QGIS_PROJECT)
    existing = [path for path in expected_outputs if path.exists()]
    if existing and not OUTPUT_MARKER.is_file():
        recoverable_map_data = existing == [MAP_DATA_FILE]
        if recoverable_map_data:
            connection = sqlite3.connect(MAP_DATA_FILE)
            try:
                marker = connection.execute(
                    """
                    SELECT description
                    FROM gpkg_contents
                    WHERE table_name = ?
                    """,
                    (MAP_DATA_LAYER,),
                ).fetchone()
                feature_count = connection.execute(
                    f'SELECT COUNT(*) FROM "{MAP_DATA_LAYER}"'
                ).fetchone()[0]
            finally:
                connection.close()
            recoverable_map_data = (
                marker is not None
                and marker[0] == OUTPUT_MARKER_CONTENT
                and feature_count == 735
            )
        if not recoverable_map_data:
            raise FileExistsError(
                "Map output already exists without the pipeline ownership "
                "marker; no files were overwritten: "
                + ", ".join(str(path) for path in existing)
            )
    if OUTPUT_MARKER.is_file():
        marker = json.loads(OUTPUT_MARKER.read_text(encoding="utf-8"))
        if marker.get("description") != OUTPUT_MARKER_CONTENT:
            raise RuntimeError(
                f"Unexpected map output marker contents in {OUTPUT_MARKER}."
            )


def _write_map_geopackage(spatial: gpd.GeoDataFrame) -> None:
    _check_existing_outputs()
    map_data = spatial.copy()
    if map_data.geometry.name != "geometry":
        map_data = map_data.rename_geometry("geometry")
    map_data["yield_unit_note"] = (
        "Production / area; source units not verified"
    )
    if "state" not in map_data or "district" not in map_data:
        raise ValueError("Spatial output must have district and state fields.")

    fd, temporary_name = tempfile.mkstemp(
        prefix="india_rice_yield_",
        suffix=".gpkg",
        dir=MAP_OUTPUT,
    )
    os.close(fd)
    temporary_path = Path(temporary_name)
    try:
        map_data.to_file(
            temporary_path,
            layer=MAP_DATA_LAYER,
            driver="GPKG",
            index=False,
        )
        connection = sqlite3.connect(temporary_path)
        try:
            connection.execute(
                """
                UPDATE gpkg_contents
                SET description = ?
                WHERE table_name = ?
                """,
                (OUTPUT_MARKER_CONTENT, MAP_DATA_LAYER),
            )
            connection.commit()
        finally:
            connection.close()

        validation = gpd.read_file(
            temporary_path,
            layer=MAP_DATA_LAYER,
        )
        if len(validation) != 735 or validation.crs.to_epsg() != 4326:
            raise RuntimeError(
                "Temporary map GeoPackage failed feature count or CRS validation."
            )
        if "crop_yield" not in validation.columns:
            raise RuntimeError("Temporary map GeoPackage lacks crop_yield.")
        del validation
        gc.collect()
        if MAP_DATA_FILE.exists():
            MAP_DATA_FILE.unlink()
        os.replace(temporary_path, MAP_DATA_FILE)
    finally:
        temporary_path.unlink(missing_ok=True)


def _find_qgis_python_launcher() -> Path:
    configured = os.getenv("QGIS_PYTHON_BAT")
    if configured:
        candidate = Path(configured)
        if not candidate.is_file():
            raise FileNotFoundError(
                f"QGIS_PYTHON_BAT does not exist: {candidate}"
            )
        return candidate

    roots = [
        Path(os.getenv("ProgramFiles", r"C:\Program Files")),
        Path(os.getenv("ProgramFiles(x86)", r"C:\Program Files (x86)")),
    ]
    installations = []
    for root in roots:
        if root.is_dir():
            installations.extend(
                child / "bin" / "python-qgis.bat"
                for child in root.iterdir()
                if child.is_dir()
                and (child / "bin" / "python-qgis.bat").is_file()
            )
    if not installations:
        raise FileNotFoundError(
            "QGIS Python was not found. Install QGIS or set QGIS_PYTHON_BAT "
            "to the full path of its python-qgis.bat launcher."
        )

    def version_key(path: Path) -> tuple[int, ...]:
        match = re.search(r"QGIS\s+(\d+(?:\.\d+)+)", str(path.parent.parent))
        return tuple(int(part) for part in match.group(1).split(".")) if match else ()

    return max(installations, key=version_key)


def _run_qgis_worker() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--qgis-worker", action="store_true")
    parser.add_argument("--input", required=True)
    parser.add_argument("--image", required=True)
    parser.add_argument("--pdf", required=True)
    parser.add_argument("--project", required=True)
    arguments = parser.parse_args()
    _create_qgis_layout(
        Path(arguments.input),
        Path(arguments.image),
        Path(arguments.pdf),
        Path(arguments.project),
    )


def _create_qgis_layout(
    input_gpkg: Path,
    image_path: Path,
    pdf_path: Path,
    project_path: Path,
) -> None:
    from qgis.PyQt.QtCore import Qt
    from qgis.PyQt.QtGui import QColor, QFont
    from qgis.core import (
        Qgis,
        QgsApplication,
        QgsClassificationJenks,
        QgsColorRamp,
        QgsCoordinateReferenceSystem,
        QgsCoordinateTransform,
        QgsFillSymbol,
        QgsGradientColorRamp,
        QgsLayoutExporter,
        QgsLayoutItemLabel,
        QgsLayoutItemLegend,
        QgsLayoutItemMap,
        QgsLayoutItemScaleBar,
        QgsLayoutPoint,
        QgsLayoutSize,
        QgsProject,
        QgsUnitTypes,
        QgsVectorLayer,
        QgsGraduatedSymbolRenderer,
    )

    prefix = os.getenv("QGIS_PREFIX_PATH")
    if prefix:
        QgsApplication.setPrefixPath(prefix, True)
    application = QgsApplication([], False)
    application.initQgis()
    project = QgsProject.instance()
    try:
        project.clear()
        project.setTitle("India Rice Yield District Choropleth")
        project.setCrs(QgsCoordinateReferenceSystem(MAP_CRS))
        layer_source = f"{input_gpkg}|layername={MAP_DATA_LAYER}"
        layer = QgsVectorLayer(layer_source, "District Rice Yield", "ogr")
        if not layer.isValid():
            raise RuntimeError(
                f"QGIS could not load the map data layer: {layer_source}"
            )
        if layer.featureCount() != 735:
            raise RuntimeError(
                f"QGIS loaded {layer.featureCount()} features instead of 735."
            )
        if layer.fields().indexFromName("crop_yield") < 0:
            raise RuntimeError("QGIS map layer does not contain crop_yield.")
        project.addMapLayer(layer)

        symbol = QgsFillSymbol.createSimple(
            {
                "color": "#a1d99b",
                "outline_color": "#ffffff",
                "outline_width": "0.18",
                "outline_width_unit": "MM",
            }
        )
        ramp: QgsColorRamp = QgsGradientColorRamp(
            QColor("#f7fcf5"),
            QColor("#00441b"),
        )
        renderer = QgsGraduatedSymbolRenderer.createRenderer(
            layer,
            "crop_yield",
            5,
            QgsGraduatedSymbolRenderer.Jenks,
            symbol,
            ramp,
        )
        if renderer is None:
            raise RuntimeError(
                "QGIS could not create the Natural Breaks (Jenks) renderer."
            )
        renderer.setClassificationMethod(QgsClassificationJenks())
        renderer.updateColorRamp(ramp)
        ranges = renderer.ranges()
        if len(ranges) != 5:
            raise RuntimeError(
                f"Expected 5 Jenks classes, QGIS created {len(ranges)}."
            )
        layer.setRenderer(renderer)
        layer.triggerRepaint()

        layout = project.layoutManager().layoutByName("India Rice Yield")
        if layout is not None:
            project.layoutManager().removeLayout(layout)
        from qgis.core import QgsPrintLayout

        layout = QgsPrintLayout(project)
        layout.initializeDefaults()
        layout.setName("India Rice Yield")
        page = layout.pageCollection().pages()[0]
        page.setPageSize(QgsLayoutSize(420, 297, QgsUnitTypes.LayoutMillimeters))

        map_item = QgsLayoutItemMap(layout)
        map_item.attemptMove(QgsLayoutPoint(10, 32))
        map_item.attemptResize(QgsLayoutSize(292, 230))
        map_item.setCrs(QgsCoordinateReferenceSystem(MAP_CRS))
        map_item.setLayers([layer])
        map_item.setKeepLayerSet(True)
        map_item.setFrameEnabled(True)
        map_transform = QgsCoordinateTransform(
            layer.crs(),
            QgsCoordinateReferenceSystem(MAP_CRS),
            project,
        )
        extent = map_transform.transformBoundingBox(layer.extent())
        extent.scale(1.05)
        map_item.zoomToExtent(extent)
        layout.addLayoutItem(map_item)

        title = QgsLayoutItemLabel(layout)
        title.setText("INDIA | DISTRICT-LEVEL RICE YIELD")
        title.setFont(QFont("Arial", 20, QFont.Weight.Bold))
        title.setFontColor(QColor("#143d24"))
        title.attemptMove(QgsLayoutPoint(10, 7))
        title.attemptResize(QgsLayoutSize(390, 18))
        layout.addLayoutItem(title)

        subtitle = QgsLayoutItemLabel(layout)
        subtitle.setText(
            "District totals across all valid source years | "
            "Yield = total production / total area"
        )
        subtitle.setFont(QFont("Arial", 10))
        subtitle.attemptMove(QgsLayoutPoint(11, 24))
        subtitle.attemptResize(QgsLayoutSize(390, 8))
        layout.addLayoutItem(subtitle)

        legend = QgsLayoutItemLegend(layout)
        legend.setTitle("Rice yield")
        legend.setLinkedMap(map_item)
        legend.setAutoUpdateModel(False)
        legend.attemptMove(QgsLayoutPoint(309, 43))
        legend.attemptResize(QgsLayoutSize(100, 82))
        layout.addLayoutItem(legend)

        north = QgsLayoutItemLabel(layout)
        north.setText("N\n↑")
        north.setFont(QFont("Arial", 18, QFont.Weight.Bold))
        north.setHAlign(Qt.AlignmentFlag.AlignHCenter)
        north.setVAlign(Qt.AlignmentFlag.AlignVCenter)
        north.attemptMove(QgsLayoutPoint(277, 36))
        north.attemptResize(QgsLayoutSize(15, 23))
        layout.addLayoutItem(north)

        scale_bar = QgsLayoutItemScaleBar(layout)
        scale_bar.setStyle("Single Box")
        scale_bar.setLinkedMap(map_item)
        scale_bar.setUnits(Qgis.DistanceUnit.Kilometers)
        scale_bar.setUnitsPerSegment(100)
        scale_bar.setNumberOfSegments(2)
        scale_bar.setNumberOfSegmentsLeft(0)
        scale_bar.setUnitLabel("km")
        scale_bar.setFont(QFont("Arial", 8))
        scale_bar.setBackgroundEnabled(True)
        scale_bar.setBackgroundColor(QColor("#ffffff"))
        scale_bar.applyDefaultSize()
        scale_bar.attemptMove(QgsLayoutPoint(14, 267))
        layout.addLayoutItem(scale_bar)

        source_note = QgsLayoutItemLabel(layout)
        source_note.setText(
            "DATA SOURCE\n"
            "District polygons: project GeoPackage,\n"
            "735 features, EPSG:4326.\n"
            "Rice statistics: public.agriculture;\n"
            "exact duplicate rows excluded.\n\n"
            "METHOD\n"
            "Area and production summed by\n"
            "district; yield = production / area.\n"
            "Five Natural Breaks (Jenks) classes;\n"
            "green colour ramp.\n\n"
            "LIMITATION\n"
            "Area/production units are unknown.\n"
            "Unmatched districts are not mapped.\n"
            "State assignments use the legacy\n"
            "693-district EPSG:4326 reference."
        )
        source_note.setFont(QFont("Arial", 8))
        source_note.setFrameEnabled(True)
        source_note.setMargin(4)
        source_note.attemptMove(QgsLayoutPoint(310, 137))
        source_note.attemptResize(QgsLayoutSize(100, 94))
        layout.addLayoutItem(source_note)

        footer = QgsLayoutItemLabel(layout)
        footer.setText(
            "Source units are unverified. Blank districts indicate no reliable "
            "agricultural-to-boundary match."
        )
        footer.setFont(QFont("Arial", 8, QFont.Weight.Normal, True))
        footer.setFontColor(QColor("#555555"))
        footer.attemptMove(QgsLayoutPoint(11, 282))
        footer.attemptResize(QgsLayoutSize(385, 8))
        layout.addLayoutItem(footer)

        project.layoutManager().addLayout(layout)
        project.setFileName(str(project_path))
        if not project.write():
            raise RuntimeError(f"QGIS failed to save project: {project_path}")
        image_settings = QgsLayoutExporter.ImageExportSettings()
        image_settings.dpi = 300
        image_exporter = QgsLayoutExporter(layout)
        image_result = image_exporter.exportToImage(
            str(image_path), image_settings
        )
        if image_result != QgsLayoutExporter.Success:
            raise RuntimeError(
                f"QGIS PNG export failed with result code {image_result}."
            )
        pdf_settings = QgsLayoutExporter.PdfExportSettings()
        pdf_settings.dpi = 300
        pdf_exporter = QgsLayoutExporter(layout)
        pdf_result = pdf_exporter.exportToPdf(str(pdf_path), pdf_settings)
        if pdf_result != QgsLayoutExporter.Success:
            raise RuntimeError(
                f"QGIS PDF export failed with result code {pdf_result}."
            )
    finally:
        project.clear()
        application.exitQgis()


def generate_qgis_map(
    spatial: gpd.GeoDataFrame | None = None,
) -> dict[str, Path]:
    MAP_OUTPUT.mkdir(parents=True, exist_ok=True)
    _check_existing_outputs()
    if spatial is None:
        spatial = _read_spatial_data()
    _write_map_geopackage(spatial)

    launcher = _find_qgis_python_launcher()
    temporary_paths = [
        MAP_OUTPUT / f".India_Rice_Yield_Map_{suffix}.tmp{extension}"
        for suffix, extension in (
            ("image", ".png"),
            ("pdf", ".pdf"),
            ("project", ".qgz"),
        )
    ]
    command_arguments = [
        str(launcher),
        str(Path(__file__).resolve()),
        "--qgis-worker",
        "--input",
        str(MAP_DATA_FILE),
        "--image",
        str(temporary_paths[0]),
        "--pdf",
        str(temporary_paths[1]),
        "--project",
        str(temporary_paths[2]),
    ]
    command = "call " + subprocess.list2cmdline(command_arguments)
    try:
        completed = subprocess.run(
            command,
            check=False,
            cwd=MAP_OUTPUT,
            env={
                **os.environ,
                "QT_QPA_PLATFORM": "offscreen",
                "QT_QPA_FONTDIR": str(
                    Path(os.getenv("WINDIR", r"C:\Windows")) / "Fonts"
                ),
                "PYTHONPATH": str(PROJECT_ROOT)
                + os.pathsep
                + os.getenv("PYTHONPATH", ""),
            },
            capture_output=True,
            text=True,
            shell=True,
        )
        if completed.returncode:
            raise RuntimeError(
                "QGIS map generation failed with exit code "
                f"{completed.returncode}.\n"
                f"QGIS output:\n{completed.stdout}\n{completed.stderr}"
            )

        for temp_path in temporary_paths:
            if not temp_path.is_file() or temp_path.stat().st_size == 0:
                raise RuntimeError(
                    f"QGIS reported success but output is missing: {temp_path}"
                )

        for temporary_path, final_path in zip(
            temporary_paths, (MAP_IMAGE, MAP_PDF, QGIS_PROJECT)
        ):
            os.replace(temporary_path, final_path)
    finally:
        for temporary_path in temporary_paths:
            temporary_path.unlink(missing_ok=True)
    OUTPUT_MARKER.write_text(
        json.dumps(
            {
                "description": OUTPUT_MARKER_CONTENT,
                "qgis_python_launcher": str(launcher),
                "project": QGIS_PROJECT.name,
                "png": MAP_IMAGE.name,
                "pdf": MAP_PDF.name,
                "data": MAP_DATA_FILE.name,
                "crs": MAP_CRS,
                "classes": 5,
                "classification": "Natural Breaks (Jenks)",
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    LOGGER.info(
        "Generated QGIS PNG, PDF, and project with 5 Jenks classes: %s",
        MAP_OUTPUT,
    )
    return {
        "image": MAP_IMAGE,
        "pdf": MAP_PDF,
        "project": QGIS_PROJECT,
        "data": MAP_DATA_FILE,
    }


if __name__ == "__main__" and "--qgis-worker" in sys.argv:
    _run_qgis_worker()
